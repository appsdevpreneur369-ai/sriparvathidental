function treatmentRows() {
  return services.categories.map((cat, i) => {
    const docs = [...new Set([...cat.doctors, ...cat.subTreatments.flatMap((s) => s.doctors ?? [])])].map((id) => byId[id].displayName);
    return {
      title: cat.title,
      category: cat.shortTitle,
      description: `${cat.subTreatments.map((s) => s.title).join(' · ')}. With ${docs.join(' and ')}.${cat.confirmSpecialist ? ' May involve a visiting specialist (to be confirmed).' : ''} ${services.priceNote}`,
      displayOrder: i,
    };
  });
}

