const approved = (f) => f.status === 'approved';
const DAY = { monday: 'Monday', tuesday: 'Tuesday', wednesday: 'Wednesday', thursday: 'Thursday', friday: 'Friday', saturday: 'Saturday', sunday: 'Sunday' };
const byId = Object.fromEntries(doctors.map((d) => [d.id, d]));
// Same wording as the website's formatter (src/lib/hours.ts → hoursSummary), computed from content.
const t12 = (t) => { const [h, m] = t.split(':').map(Number); return `${h % 12 || 12}:${String(m).padStart(2, '0')} ${h >= 12 ? 'PM' : 'AM'}`; };
const part = (t) => (Number(t.slice(0, 2)) < 12 ? 'Morning' : Number(t.slice(0, 2)) < 17 ? 'Afternoon' : 'Evening');
const sessionsText = (ss) => (ss.length === 1 ? `${t12(ss[0].opens)} – ${t12(ss[0].closes)}` : ss.map((x) => `${part(x.opens)} ${t12(x.opens)} – ${t12(x.closes)}`).join(' & '));
const groups = [];
for (const d of clinic.hours.days) {
  const last = groups[groups.length - 1];
  if (last && JSON.stringify(last.sessions) === JSON.stringify(d.sessions)) last.days.push(d.day);
  else groups.push({ days: [d.day], sessions: d.sessions });
}
const hoursText = groups
  .map((g) => `${g.days.length > 1 ? `${DAY[g.days[0]]}–${DAY[g.days[g.days.length - 1]]}` : DAY[g.days[0]]}${g.sessions.length ? `, ${sessionsText(g.sessions)}` : ' closed'}`)
  .join('; ');
const a = clinic.address;
const address = [a.doorNumber, a.street, a.landmark && `near ${a.landmark}`, a.locality, `${a.region}${a.postalCode ? ` ${a.postalCode}` : ''}`].filter(Boolean).join(', ');
// PLACEHOLDER login emails: plus-aliases of the account owner's own test inbox (same convention as the other tenant files).
